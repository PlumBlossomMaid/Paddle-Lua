-- tools/gen/scan_pd_op.lua
-- Scan the build-tree pd_op.h and emit tools/gen/pd_op_builds.lua: for
-- every paddle::dialect op class, the exact set of `static void Build`
-- overload shapes. emit_capi.lua's P15 trace branch calls the typed
-- <Op>Op::Build, and the overload shapes VARY per op (ScaleOp:
-- (Value, AttributeMap); ArangeOp: (Value,Value,Value, DataType, Place)
-- with NO input-carrying AttributeMap overload -- pd_op.h:47674-47677),
-- so they must be read from the header, never guessed (anti-hallucination
-- rule, AGENTS.md sec.4). Class names also come from the header (the
-- snake_case->PascalCase guess breaks, e.g. div_scale).
--
-- Usage:
--   lua tools/gen/scan_pd_op.lua <pd_op.h> <out.lua> [--sha <short-sha>]
--
-- Output is committed (like index_semantics.lua) so regen_diff stays
-- hermetic: emit_capi reads the table, not pd_op.h. Re-run this scanner
-- when bumping the pinned Paddle sha.

local src, out, sha = nil, nil, "unknown"
local n = select("#", ...)
local i = 1
while i <= n do
  local a = select(i, ...)
  if a == "--sha" then
    i = i + 1
    sha = select(i, ...)
  elseif a and string.sub(a, 1, 1) ~= "-" and src == nil then
    src = a
  elseif a and string.sub(a, 1, 1) ~= "-" then
    out = a
  else
    io.stderr:write("scan_pd_op: unknown arg '" .. tostring(a) .. "'\n")
    os.exit(2)
  end
  i = i + 1
end
if not src or not out then
  io.stderr:write(
    "usage: lua tools/gen/scan_pd_op.lua <pd_op.h> <out.lua> "
    .. "[--sha <git-sha>]\n")
  os.exit(2)
end

local f = assert(io.open(src, "rb"))
local text = f:read("*a")
f:close()

-- split an arg list at top-level commas (defaults may contain parens,
-- e.g. `=phi::CPUPlace()`)
local function split_args(s)
  local args, depth, cur = {}, 0, {}
  for c in string.gmatch(s, ".") do
    if c == "(" or c == "<" or c == "{" or c == "[" then
      depth = depth + 1
    elseif c == ")" or c == ">" or c == "}" or c == "]" then
      depth = depth - 1
    end
    if c == "," and depth == 0 then
      args[#args + 1] = table.concat(cur)
      cur = {}
    else
      cur[#cur + 1] = c
    end
  end
  local last = table.concat(cur)
  if string.match(last, "%S") then args[#args + 1] = last end
  return args
end

-- one Build overload's arg list -> { values = K, attrmap = true }
-- or { values = K, trailing = { "float", ... } }, or nil if the shape is
-- unusable for the trace branch (non-Value arg before a Value, etc.)
local function classify(argstr)
  -- strip the fixed (builder, argument) prefix
  local rest = string.match(argstr,
    "^%s*pir::Builder%s*&%s*builder%s*,%s*pir::OperationArgument%s*&%s*argument%s*,?(.*)$")
  if not rest then return nil end
  rest = string.match(rest, "^%s*(.-)%s*$")
  local values, trailing = 0, {}
  local seen_nonvalue = false
  if rest ~= "" then
    for _, a in ipairs(split_args(rest)) do
      a = string.gsub(a, "=.*$", "")          -- drop default value
      a = string.match(a, "^%s*(.-)%s*$")
      -- type = everything up to the last identifier (the param name)
      local ty = string.match(a, "^(.*)[%s&]+([%w_]+)$") or a
      ty = string.match(ty, "^%s*(.-)%s*$")
      ty = string.gsub(ty, "^const%s+", "")
      ty = string.gsub(ty, "&$", "")
      ty = string.match(ty, "^%s*(.-)%s*$")
      if ty == "pir::AttributeMap" then
        if seen_nonvalue then return nil end
        return { values = values, attrmap = true }
      elseif ty == "pir::Value" then
        if seen_nonvalue then return nil end
        values = values + 1
      else
        seen_nonvalue = true
        trailing[#trailing + 1] = ty
      end
    end
  end
  return { values = values, trailing = trailing }
end

local ops = {}
local cur_cls, cur_name, cur_builds = nil, nil, nil
local function flush()
  if cur_cls and cur_name and cur_builds then
    ops[cur_name] = { cls = cur_cls, builds = cur_builds }
  end
  cur_cls, cur_name, cur_builds = nil, nil, nil
end

for line in string.gmatch(text, "[^\r\n]+") do
  local cls = string.match(line, "^class%s+TEST_API%s+([%w_]+Op)%s*:")
           or string.match(line, "^class%s+([%w_]+Op)%s*:")
  if cls then
    flush()
    cur_cls, cur_builds = cls, {}
  elseif cur_cls then
    if string.match(line, "^};") then
      flush()
    else
      local nm = string.match(line, 'return "(pd_op%.[%w_]+)"')
      if nm then
        cur_name = string.sub(nm, 7)  -- strip "pd_op."
      else
        local args = string.match(line, "static void Build%((.*)%);")
        if args then
          local b = classify(args)
          if b then cur_builds[#cur_builds + 1] = b end
        end
      end
    end
  end
end
flush()

-- serialize deterministically (sorted by op name)
local names = {}
for k in pairs(ops) do names[#names + 1] = k end
table.sort(names)
local outl = {}
outl[#outl + 1] = "-- GENERATED BY tools/gen/scan_pd_op.lua FROM " .. src
outl[#outl + 1] = "-- @ " .. sha
outl[#outl + 1] = "-- DO NOT EDIT (re-run the scanner when bumping Paddle)"
outl[#outl + 1] = "return {"
for _, name in ipairs(names) do
  local o = ops[name]
  local bs = {}
  for _, b in ipairs(o.builds) do
    if b.attrmap then
      bs[#bs + 1] = "{ values = " .. b.values .. ", attrmap = true }"
    elseif #b.trailing == 0 then
      bs[#bs + 1] = "{ values = " .. b.values .. " }"
    else
      bs[#bs + 1] = "{ values = " .. b.values .. ", trailing = { \""
        .. table.concat(b.trailing, "\", \"") .. "\" } }"
    end
  end
  outl[#outl + 1] = "  [\"" .. name .. "\"] = { cls = \"" .. o.cls
    .. "\", builds = { " .. table.concat(bs, ", ") .. " } },"
end
outl[#outl + 1] = "}"
local of = assert(io.open(out, "wb"))
of:write(table.concat(outl, "\n") .. "\n")
of:close()
io.stdout:write("scan_pd_op: " .. #names .. " ops -> " .. out .. "\n")
os.exit(0)
